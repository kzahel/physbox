import { createHash } from "node:crypto";
import {
  cpSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { basename, extname, join, relative, resolve } from "node:path";
import { execFileSync } from "node:child_process";

const revision = "3a4f0da8374af61293a03021c9a0b3ebcfe67948";
const repository = resolve(import.meta.dirname, "..");
const source = join(repository, "reference", "box2d");
const destination = join(repository, "third_party", "box2d-comparator");

const actual = execFileSync("git", ["-C", source, "rev-parse", "HEAD"], {
  encoding: "utf8",
}).trim();
if (actual !== revision) {
  throw new Error(`Box2D source is ${actual}; expected ${revision}`);
}
const dirty = execFileSync(
  "git",
  ["-C", source, "status", "--porcelain=v1", "--untracked-files=all"],
  { encoding: "utf8" },
).trim();
if (dirty) {
  throw new Error(`Box2D source checkout is dirty:\n${dirty}`);
}

rmSync(destination, { recursive: true, force: true });
mkdirSync(join(destination, "include", "box2d"), { recursive: true });
mkdirSync(join(destination, "src"), { recursive: true });

const copied = [];
function copy(sourcePath, destinationPath) {
  mkdirSync(resolve(destinationPath, ".."), { recursive: true });
  cpSync(sourcePath, destinationPath);
  copied.push(destinationPath);
}

copy(join(source, "LICENSE"), join(destination, "LICENSE"));
for (const name of readdirSync(join(source, "include", "box2d")).sort()) {
  if (extname(name) === ".h") {
    copy(
      join(source, "include", "box2d", name),
      join(destination, "include", "box2d", name),
    );
  }
}
for (const name of readdirSync(join(source, "src")).sort()) {
  if ([".c", ".h"].includes(extname(name))) {
    copy(join(source, "src", name), join(destination, "src", name));
  }
}

const lines = [
  "# Generated by scripts/vendor-box2d-comparator.mjs from a clean managed checkout.",
  `revision ${revision}`,
  "upstream https://github.com/erincatto/box2d.git",
  "license MIT (see LICENSE)",
  "native-build GNU C17, BOX2D_DISABLE_SIMD, floating-point contraction disabled when supported",
  "",
];
for (const path of copied.sort()) {
  const bytes = readFileSync(path);
  const digest = createHash("sha256").update(bytes).digest("hex");
  lines.push(`${digest}  ${relative(destination, path)}`);
}
writeFileSync(
  join(destination, "SOURCE-MANIFEST.txt"),
  `${lines.join("\n")}\n`,
);

console.log(
  `Vendored ${copied.length} Box2D files from ${basename(source)} at ${revision}.`,
);
